// Resolved once per page load, then only changed by setLang(), so the toggle
// is not overridden by the URL on every t() call.
let currentLang = null;

const URL_LANG_KEYS = { 'lang_en': 'en', 'lang-en': 'en', 'lang_hr': 'hr', 'lang-hr': 'hr' };

// Reads ?lang=en / ?lang_EN / ?lang-hr (case-insensitive), then strips those
// params from the address bar so a refresh keeps the user's toggle choice.
function readUrlLang() {
    let detected = null;
    try {
        const params = new URLSearchParams(window.location.search);
        const kept = new URLSearchParams();
        let found = false;
        for (const [rawKey, rawVal] of params) {
            const k = rawKey.trim().toLowerCase();
            if (k === 'lang' || URL_LANG_KEYS[k]) {
                found = true;
                const v = k === 'lang' ? rawVal.trim().toLowerCase() : URL_LANG_KEYS[k];
                if (!detected && (v === 'en' || v === 'hr')) detected = v;
            } else {
                kept.append(rawKey, rawVal);
            }
        }
        if (found && window.history && window.history.replaceState) {
            const qs = kept.toString();
            window.history.replaceState(window.history.state, '',
                window.location.pathname + (qs ? '?' + qs : '') + window.location.hash);
        }
    } catch (_) {}
    return detected;
}

export function getLang() {
    if (currentLang) return currentLang;

    const urlLang = readUrlLang();
    if (urlLang) {
        try { localStorage.setItem('lang', urlLang); } catch (_) {}
        currentLang = urlLang;
        return currentLang;
    }
    try {
        const localLang = localStorage.getItem('lang');
        if (localLang === 'en' || localLang === 'hr') {
            currentLang = localLang;
            return currentLang;
        }
    } catch (_) {}
    currentLang = defaultLang();
    return currentLang;
}

// no-skill-issue.com is the English front door; every other host starts in Croatian.
// Only the default: a ?lang link or the toggle (saved per domain) still wins.
function defaultLang() {
    try {
        const h = window.location.hostname.toLowerCase();
        if (h === 'no-skill-issue.com' || h.endsWith('.no-skill-issue.com')) return 'en';
    } catch (_) {}
    return 'hr';
}

export function setLang(lang) {
    if (lang === 'en' || lang === 'hr') {
        currentLang = lang;
        try { localStorage.setItem('lang', lang); } catch (_) {}
        document.documentElement.lang = lang;
        applyI18n();
        // Allow scripts to react to language change (like refreshing questions)
        window.dispatchEvent(new CustomEvent('languagechanged', { detail: { lang } }));
    }
}

export function t(key) {
    const lang = getLang();
    if (I18N[lang] && I18N[lang][key]) {
        return I18N[lang][key];
    }
    return key;
}

export function applyI18n() {
    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(el => {
        const key = el.getAttribute('data-i18n');
        const translation = t(key);
        
        if (key.includes('aria')) {
            el.setAttribute('aria-label', translation);
        } else if (el.tagName === 'INPUT' && el.type === 'text') {
            el.placeholder = translation;
        } else {
            if (translation.includes('<')) {
                el.innerHTML = translation;
            } else if (el.children.length === 0) {
                el.textContent = translation;
            } else {
                // Best effort if there are children, usually we wrap text in span
                // Avoid using innerText on containers that shouldn't be overwritten.
                // Since we separated aria labels, this should now be safer.
                // However, replacing textContent for elements with children destroys them.
                // It is better to replace only text nodes, but for simplicity, 
                // we assume text-containing nodes with data-i18n don't have complex HTML we care about destroying,
                // OR they are simple wrappers.
                let hasTextNode = false;
                for (let node of el.childNodes) {
                    if (node.nodeType === Node.TEXT_NODE && node.nodeValue.trim().length > 0) {
                        node.nodeValue = translation;
                        hasTextNode = true;
                        break;
                    }
                }
                if (!hasTextNode) {
                     el.innerText = translation;
                }
            }
        }
    });

    const langBtn = document.getElementById('btn-lang-toggle');
    if (langBtn) {
        langBtn.textContent = getLang() === 'hr' ? 'ENGLISH' : 'CROATIAN';
    }
}
